import AppKit
import Combine

/// Recuerda lo último que copiaste, para poder volver a pegarlo.
///
/// macOS no avisa cuando cambia el portapapeles: hay que preguntarle. Se le
/// pregunta cada medio segundo por `changeCount`, que es un número que sube en
/// cada copia. Es barato: comparar un entero, no leer el contenido.
///
/// **Todo esto vive en memoria y nunca toca el disco.** Un historial de
/// portapapeles guardado es un archivo lleno de lo que copiaste sin pensar:
/// claves, direcciones, números de tarjeta. Al cerrar Notae se borra solo, y
/// eso es a propósito.
@MainActor
final class Portapapeles: ObservableObject {

    struct Copia: Identifiable, Equatable {
        let id = UUID()
        let texto: String
        let cuando: Date

        /// Una línea para el menú, sin saltos ni espacios de más.
        var resumen: String {
            let plano = texto
                .replacingOccurrences(of: "\n", with: " ")
                .replacingOccurrences(of: "\t", with: " ")
                .split(separator: " ")
                .joined(separator: " ")
            return plano.count > 58 ? String(plano.prefix(58)) + "…" : plano
        }
    }

    /// De lo más nuevo a lo más viejo.
    @Published private(set) var recientes: [Copia] = []

    /// Cuántas copias se recuerdan. Más allá de esto deja de ser útil y empieza
    /// a ser un archivo de cosas tuyas dando vueltas en memoria.
    static let maximo = 20

    private let pb = NSPasteboard.general
    private var ultimoConteo: Int
    private var reloj: Timer?
    /// Mientras Notae pega, el portapapeles cambia dos veces (pone el texto y
    /// lo devuelve). Eso no es una copia tuya y no se guarda.
    private var silencioHasta = Date.distantPast

    init() {
        ultimoConteo = pb.changeCount
    }

    func encender() {
        guard reloj == nil else { return }
        reloj = Timer.scheduledTimer(withTimeInterval: 0.5, repeats: true) { [weak self] _ in
            MainActor.assumeIsolated { self?.revisar() }
        }
    }

    func apagar() {
        reloj?.invalidate()
        reloj = nil
    }

    /// Ignora los cambios del portapapeles durante unos segundos.
    func silenciar(_ segundos: TimeInterval) {
        silencioHasta = Date().addingTimeInterval(segundos)
    }

    func olvidarTodo() {
        recientes.removeAll()
    }

    func olvidar(_ copia: Copia) {
        recientes.removeAll { $0.id == copia.id }
    }

    /// `NSMenuItem` solo sabe llamar a objetos de Objective-C. Esto envuelve un
    /// cierre para poder armar el menú con closures normales.
    final class Accion: NSObject {
        private let hacer: () -> Void
        init(_ hacer: @escaping () -> Void) { self.hacer = hacer }
        @objc func ejecutar() { hacer() }
    }

    // MARK: - Privado

    private func revisar() {
        let conteo = pb.changeCount
        guard conteo != ultimoConteo else { return }
        ultimoConteo = conteo
        guard Date() >= silencioHasta else { return }

        guard let item = pb.pasteboardItems?.first else { return }

        // Los gestores de contraseñas marcan lo que copian como oculto,
        // justamente para que herramientas como esta no lo guarden. Se respeta.
        let tiposReservados: Set<String> = [
            "org.nspasteboard.ConcealedType",
            "org.nspasteboard.TransientType",
            "org.nspasteboard.AutoGeneratedType"
        ]
        let tipos = Set(item.types.map(\.rawValue))
        guard tipos.isDisjoint(with: tiposReservados) else { return }

        guard let texto = pb.string(forType: .string) else { return }
        let limpio = texto.trimmingCharacters(in: .whitespacesAndNewlines)
        guard !limpio.isEmpty, limpio.count < 20_000 else { return }

        // Si copiaste lo mismo otra vez, sube al principio en vez de duplicarse.
        recientes.removeAll { $0.texto == limpio }
        recientes.insert(Copia(texto: limpio, cuando: Date()), at: 0)
        if recientes.count > Self.maximo {
            recientes.removeLast(recientes.count - Self.maximo)
        }
        // Solo el tamaño, nunca el contenido: el registro se puede leer y se
        // guarda en disco.
        Registro.di("portapapeles: copia guardada · \(limpio.count) caracteres · \(recientes.count) en memoria")
    }
}
